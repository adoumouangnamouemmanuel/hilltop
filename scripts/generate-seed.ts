const listings = [...sellerListings, ...demoListings];

const header = (purpose: string) => `-- Generated by scripts/generate-seed.ts. Don't edit by hand.\n-- ${purpose}\n\n`;

const bootstrap =
  header("Roles, the default platform config and the owner invite. Safe to run on production.") +
  `insert into public.admin_roles (id, name, description, permissions, system) values\n` +
  defaultRoles
    .map((r) => `  (${text(r.id)}, ${text(r.name)}, ${text(r.description)}, ${arr(r.permissions)}, ${bool(r.system)})`)
    .join(",\n") +
  `\non conflict (id) do nothing;\n\n` +
  `insert into public.config_releases (config, note, published_by_name)\n` +
  `select ${json(defaultConfig)}, 'Initial configuration', 'System'\n` +
  `where not exists (select 1 from public.config_releases);\n\n` +
  `insert into public.admin_members (email, name, role_id, status)\n` +
  `values (${text(OWNER_EMAIL.toLowerCase())}, ${text(OWNER_NAME)}, 'owner', 'invited')\n` +
  `on conflict (email) do nothing;\n`;

const profileRows = sellers.map(
  (s) =>
    `  (${sellerId(s.id)}, ${text(s.id)}, ${text(s.name)}, ${text(s.shop ?? null)}, ${text(s.specialty)}, ${num(s.classOf)}, ${text(s.major ?? null)}, ${text(s.responseTime)}, true, ${num(s.sales)})`,
);

const listingRows = listings.map((l) => {
  const status = l.status === "draft" ? "draft" : l.status === "sold" ? "sold" : "active";
  return `  (${text(l.id)}, ${sellerId(l.sellerId)}, ${text(l.title)}, ${text(l.description)}, ${num(l.price)}, ${num(l.originalPrice)}, ${text(l.category)}, ${text(l.condition ?? null)}, ${json(l.attributes ?? {})}, ${json(l.extra ?? [])}, ${text(l.pickup)}, ${num(l.stock)}, ${l.food ? json(l.food) : "null"}, ${bool(l.moveOut)}, ${l.promoted ? "now() + interval '7 days'" : "null"}, '${status}', now() - interval '${l.postedDaysAgo} days', ${l.views}, ${l.saves})`;
});

const photoRows = listings.flatMap((l) => l.images.map((url, i) => `  (${text(l.id)}, ${text(url)}, ${i})`));

const seed =
  header("Demo data for local development: the Ashesi sellers and their listings.") +
  `insert into public.profiles (id, handle, name, shop_name, specialty, class_of, major, response_time, verified, sales) values\n` +
  profileRows.join(",\n") +
  `\non conflict (id) do nothing;\n\n` +
  `-- ${DEMO_STUDENT.name}, a demo student whose shop is claimed when they first sign in.\n` +
  `insert into public.profiles (id, handle, name, claim_email) values (${sellerId(DEMO_STUDENT.id)}, ${text(DEMO_STUDENT.id)}, ${text(DEMO_STUDENT.name)}, ${text(DEMO_STUDENT.email)})\n` +
  `on conflict (id) do nothing;\n\n` +
  `insert into public.listings (id, seller_id, title, description, price, original_price, category, condition, attributes, extra, pickup, stock, food, move_out, promoted_until, status, posted_at, views, saves) values\n` +
  listingRows.join(",\n") +
  `\non conflict (id) do nothing;\n\n` +
  `insert into public.listing_photos (listing_id, url, position) values\n` +
  photoRows.join(",\n") +
  `\non conflict (listing_id, position) do nothing;\n`;

const dir = join(__dirname, "..", "supabase");
writeFileSync(join(dir, "bootstrap.sql"), bootstrap);
writeFileSync(join(dir, "seed.sql"), seed);
console.log(`Wrote bootstrap.sql and seed.sql: ${sellers.length} sellers, ${listings.length} listings, ${photoRows.length} photos.`);
