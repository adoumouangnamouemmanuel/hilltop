const text = (v: string | null | undefined) => (v === null || v === undefined ? "null" : `'${v.replace(/'/g, "''")}'`);
const json = (v: unknown) => `${text(JSON.stringify(v))}::jsonb`;
const arr = (v: string[]) => `array[${v.map(text).join(", ")}]::text[]`;
const num = (v: number | null | undefined) => (v === null || v === undefined ? "null" : String(v));
const bool = (v: boolean | undefined) => (v ? "true" : "false");
// Stable ids so re-seeding keeps the same profiles.
const sellerId = (id: string) => `md5('seller:${id}')::uuid`;

