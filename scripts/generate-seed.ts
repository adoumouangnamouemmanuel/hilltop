/*
 * Writes the database seed files from the shared TypeScript data, so the database
 * and the apps agree.
 *
 *   supabase/bootstrap.sql  roles, the default platform config and the owner invite.
 *                           Safe for production.
 *   supabase/seed.sql       demo sellers, listings and photos. Local development only,
 *                           until the sellers agree to be listed.
 *
 * Run: npm run db:seed-files
 */
