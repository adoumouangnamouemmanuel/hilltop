import { unsplash as img } from "./catalog";

/** A condition label, e.g. "Like new". Allowed values come from the platform config. */
export type Condition = string;
/** A pickup spot name. Allowed values come from the platform config. */
export type PickupSpot = string;

export type AttrValue = string | number | boolean;

export type Seller = {
  id: string;
  name: string;
  /** Business name, e.g. "Eyecon", shown alongside the seller's name. */
  shop?: string;
  /** What they sell, in a few words. */
  specialty: string;
  /** Optional, only shown when the student adds it. */
  classOf?: number;
  major?: string;
  rating: number;
  reviews: number;
  sales: number;
  responseTime: string;
  joined: string;
};

/** "expired" is derived: an active listing older than the configured expiry. Sellers renew it to bring it back. */
export type ListingStatus = "active" | "sold" | "draft" | "expired";

export type FoodOrdering = {
  /** Same-day orders close at this time (24h "HH:MM"). Later orders are for the next day. */
  cutoff: string;
  /** Pickup windows offered to the buyer. */
  slots: string[];
};

export type Listing = {
  id: string;
  title: string;
  price: number;
  originalPrice?: number;
  category: string;
  condition?: Condition;
  images: string[];
  description: string;
  /** Values for the category's attribute schema, keyed by attribute key. */
  attributes?: Record<string, AttrValue>;
  /** Free-form details a seller adds beyond the schema. */
  extra?: [string, string][];
  sellerId: string;
  pickup: PickupSpot;
  postedDaysAgo: number;
  promoted?: boolean;
  moveOut?: boolean;
  /** For items sold in batches, like food. */
  stock?: number;
  /** Defaults to "active". Drafts are only visible to their owner. */
  status?: ListingStatus;
  /** Ordering rules for made-to-order items like food. */
  food?: FoodOrdering;
  saves: number;
  views: number;
};

